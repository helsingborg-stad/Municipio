<?php

declare(strict_types=1);

namespace Municipio\Search\Index;

use AcfService\AcfService;
use \Municipio\Search\Index\Helper\Options as Options;
use WpService\WpService;

class App
{
    public function __construct(private WpService $wpService, private AcfService $acfService)
    {
    }

    public function enable():void {
        //Config page
        new \Municipio\Search\Index\Admin\Settings($this->wpService, $this->acfService);

        // Defer ACF-dependent configuration reads until ACF is initialized.
        $this->wpService->addAction('acf/init', [$this, 'initializeConfiguredFeatures'], 20);

        //Admin pages
        new \Municipio\Search\Index\Admin\Post($this->wpService);

        //Cli api (bulk actions)
        if (defined('WP_CLI') && constant('WP_CLI') == true) {
            new \Municipio\Search\Index\Bulk();
        }
    }

    /**
     * Initialize features that depend on configuration stored in ACF.
     *
     * @return void
     */
    public function initializeConfiguredFeatures()
    {
        if (!Options::isConfigured()) {
            $this->wpService->addAction('admin_notices', [$this, 'displayAdminNotice']);
            return;
        }

        new \Municipio\Search\Index\Index();
        new \Municipio\Search\Index\Search();
        new \Municipio\Search\Index\Facetting();
    }

    /**
     * Throw warning for undefined constants.
     *
     * @return void
     */
    public function displayAdminNotice()
    {
        echo '<div class="notice notice-error"><p>';
        $this->wpService->_e('Required constants undefined, algolia will not run before setting 
            ALGOLIAINDEX_APPLICATION_ID and ALGOLIAINDEX_API_KEY constants. 
            Optionally, you may set ALGOLIAINDEX_INDEX_NAME 
            otherwise it will be autogenerated.', 'municipio');
        echo '</p></div>';
    }
}
